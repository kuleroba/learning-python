# list data structures
names=["wako", "roba", "diba" ,"dadole" ,"doge"]
print(f"my name is {names[0]}" )

# tuple data structure
fruit=("mango","banana","apple","pawpaw","pineapple")
print(f"my fruit is {fruit[0]}" )

# set data structures
cars={"mercedes","lamborghini","ferari","toyota","porshe"}
print(f"my cars is {cars}")

# dictionary data structures

staff={"name":"wako","Age":20,"course":"BSEE","additional academia":"dev"}
print(f"staff name:{staff['name']}")
print(f"staff age:{staff['Age']}")
print(f"staff course:{staff['course']}")
print(f"staff additional academia:{staff['additional academia']}")